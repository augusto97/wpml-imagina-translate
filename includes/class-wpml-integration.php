<?php
/**
 * WPML Integration - creates and links translated posts.
 *
 * API surface
 * -----------
 * WPML documents its hooks (`apply_filters`/`do_action`) as the only public,
 * stability-guaranteed surface. The global `$sitepress` object and the
 * `icl_*` functions still work in 4.9 but are undocumented or deprecated, so
 * they are used only as fallbacks here.
 *
 * Why post writes go through wp_insert_post()/wp_update_post()
 * -----------------------------------------------------------
 * A previous version wrote `post_content` with `$wpdb->update()` on the posts
 * table to dodge `content_save_pre` filters. That had two serious consequences:
 *
 *  1. `save_post` never fired, so WPML's own `WPML_TM_Post_Actions` never
 *     recorded translation status. Translations kept showing as missing or
 *     "needs update" in the WPML dashboard even though they existed.
 *     Elementor, SEO plugins and caches were equally left stale.
 *
 *  2. It bypassed `wp_filter_post_kses`, storing unfiltered markup for users
 *     without the `unfiltered_html` capability — a stored-XSS vector, since
 *     the content is generated by an external AI service.
 *
 * Block markup survives `wp_update_post()` perfectly well: that is how the
 * block editor itself saves. The only filter that genuinely corrupts block
 * markup is `balanceTags`, which is disabled here for the duration of the
 * write and restored immediately afterwards.
 */

